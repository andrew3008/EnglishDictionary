package space.br1440.platform.tracing.autoconfigure.control.jmx;

import java.util.Objects;

enum JmxClientFailureCode {

    METADATA_GATE_FAILED,
    METADATA_ENDPOINT_DISAPPEARED,
    METADATA_TRANSPORT_SECURITY_FAILED,

    STATUS_JMX_WIRE_TYPE_VIOLATION,
    STATUS_NULL_VALUE,
    STATUS_ATTRIBUTE_DRIFT,
    STATUS_ENDPOINT_DISAPPEARED,
    STATUS_PROVIDER_INVOCATION_FAILED,
    STATUS_RESPONSE_CONTRACT_FAILED,
    STATUS_RESPONSE_DECODE_FAILED,
    STATUS_TRANSPORT_SECURITY_FAILED,
    STATUS_TRANSPORT_FAILED,

    MUTATION_JMX_WIRE_TYPE_VIOLATION,
    MUTATION_ENCODING_FAILED,
    MUTATION_SIGNATURE_DRIFT,
    MUTATION_ENDPOINT_DISAPPEARED,
    MUTATION_PROVIDER_INVOCATION_FAILED,
    MUTATION_RESPONSE_CONTRACT_FAILED,
    MUTATION_RESPONSE_DECODE_FAILED,
    MUTATION_RESPONSE_TYPE_INVALID,

    MUTATION_OUTCOME_UNKNOWN,
    MUTATION_TRANSPORT_SECURITY_FAILED,
    MUTATION_TRANSPORT_FAILED,

    MUTATION_UNEXPECTED_ERROR,

    TERMINALLY_INVALIDATED;

    private static final String PREFIX = "JMX_CLIENT_";

    String token() {
        return PREFIX + name();
    }

    String message(String detail) {
        Objects.requireNonNull(detail, "detail");
        return token() + ": " + detail;
    }
}
