package space.br1440.platform.tracing.otel.javaagent.bootstrap.verification;

/**
 * Коды отказа сверки контролируемого дистрибутива агента.
 * <p>
 * Имя константы передаётся в readiness-снимке как есть и служит единственным
 * внешним представлением кода. Переименование или удаление константы нарушает
 * контракт с потребителями снимка.
 */
public enum VerificationFailureCode {

    /**
     * Обязательные артефакты подтверждения подлинности дистрибутива отсутствуют
     * или не могут быть прочитаны.
     */
    DISTRIBUTION_EVIDENCE_MISSING,

    /**
     * Проверка дистрибутива выполнена, но его идентификатор или контрольная сумма
     * не совпадают с ожидаемыми значениями.
     */
    DISTRIBUTION_MISMATCH,

    /**
     * При активации расширения перехвачен {@link LinkageError}:
     * бинарный интерфейс агента и расширения несовместим.
     */
    EXTENSION_LINKAGE_ERROR

}
